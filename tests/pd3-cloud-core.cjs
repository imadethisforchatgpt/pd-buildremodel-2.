const assert = require('node:assert/strict');
const C = require('../js/pd3-cloud-core.js');
const original = {...C.empty(),clients:[{name:'Synthetic customer',address:'Billing',notes:'Saved history'}],projects:[{name:'Cabinets',status:'In Progress',measurements:'52 x 97',materials:'Plywood',warranty:'1 year'}],estimates:[{client:'Synthetic customer',contentBlocks:[{type:'photo',src:'photo-local-1'}],customFutureField:{value:42}}],invoices:[{sourceEstimate:0,total:100,paid:120,payments:[{amount:120,id:'payment-1'}]}],businessProfile:{preparedBy:'Papo Delvalle'},unknownTopLevel:{retain:'yes'}};
const payload = C.encode(original);
let cloud = C.next(null,0,payload,'mutation-123456','server-time');
assert.deepEqual(C.decode(cloud),original,'Preserve all business fields and photo references');
const deviceB = C.decode(cloud);
const updateA = {...original,clients:[...original.clients,{name:'New client'}]};
cloud = C.next(cloud,1,C.encode(updateA),'mutation-abcdef','server-time');
assert.throws(() => C.next(cloud,1,C.encode({...deviceB,invoices:[]}), 'mutation-stale','server-time'),e=>e.code==='pd3/conflict');
assert.equal(C.decode(cloud).invoices[0].paid,120);
assert.equal(C.next(cloud,1,C.encode(updateA),'mutation-abcdef','server-time'),null);
assert.equal(C.decode(cloud).clients.length,2);
assert.throws(()=>C.encode({...original,photos:'data:image/jpeg;base64,AAAA'}),/Photo bytes/);
assert.throws(()=>C.encode({...original,notes:'x'.repeat(700001)}),/cloud limit/);
assert.throws(()=>C.encode({...original,notes:'😀'.repeat(180000)}),/cloud limit/);
assert.throws(()=>C.validate(JSON.parse('{"clients":[],"estimates":[],"invoices":[],"templates":[],"feedback":[],"__proto__":{}}')),/Unsafe/);
assert.throws(()=>C.decode({...cloud,revision:'2'}),/Unsupported/);
assert.throws(()=>C.validate({clients:[]}),/Invalid estimates/);
console.log('PASS: lossless records/payments, offline conflicts, idempotent retry, photo exclusion, byte limits, backup validation');

assert.throws(()=>C.validate({...C.empty(),clients:[null]}),/Invalid clients record/);
assert.throws(()=>C.validate({...C.empty(),projects:{}}),/Invalid projects records/);
